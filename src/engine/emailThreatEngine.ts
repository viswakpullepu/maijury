export function getRegistrableDomain(domain: string): string {
  if (!domain || typeof domain !== 'string') return '';
  const clean = domain.toLowerCase().trim().replace(/^@+/, '');
  const parts = clean.split('.');
  if (parts.length <= 2) return parts.join('.');
  const secondLast = parts[parts.length - 2];
  const last = parts[parts.length - 1];
  if (['co', 'com', 'org', 'net', 'edu', 'gov', 'ac'].includes(secondLast) && last.length === 2) {
    return parts.slice(-3).join('.');
  }
  return parts.slice(-2).join('.');
}

const ENTERPRISE_ECOSYSTEM_DOMAINS: Record<string, string[]> = {
  microsoft: ['microsoft.com', 'outlook.com', 'office365.com', 'live.com', 'windowsazure.com', 'office.com', 'msn.com', 'microsoftonline.com'],
  google: ['google.com', 'googlemail.com', 'gmail.com', 'google-analytics.com', 'googleusercontent.com'],
  apple: ['apple.com', 'icloud.com', 'me.com'],
  amazon: ['amazon.com', 'amazonaws.com', 'amazonses.com'],
  stripe: ['stripe.com']
};

export function areDomainsInSameEcosystem(d1: string, d2: string): boolean {
  if (!d1 || !d2) return false;
  const r1 = getRegistrableDomain(d1);
  const r2 = getRegistrableDomain(d2);
  if (r1 && r2 && r1 === r2) return true;
  for (const group of Object.values(ENTERPRISE_ECOSYSTEM_DOMAINS)) {
    if (group.includes(r1) && group.includes(r2)) {
      return true;
    }
  }
  return false;
}

