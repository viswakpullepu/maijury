/**
 * Normalizes any threat vector identifier or alias into its canonical catalog ID.
 * Supports:
 * - 'CRYPTO-01' or 'CRYPTO-1' -> 'CRY-01'
 * - 'LINK-01' or 'LINK-1'     -> 'LNK-01'
 * - 'INJ-01' or 'INJ-1'       -> 'LLM-01'
 * - 'HDR-1'                   -> 'HDR-01'
 * - Case-insensitive & trimmed inputs
 * - Direct vector codes (e.g. 'SPF_HARD_FAIL' -> 'HDR-01')
 */
export function normalizeVectorId(idOrCode: string): string {
  if (!idOrCode || typeof idOrCode !== 'string') return '';
  const clean = idOrCode.trim().toUpperCase();

  // 1. Direct code to canonical ID mapping
  const byCode = EMAIL_THREAT_VECTORS_CATALOG.find(v => v.code === clean);
  if (byCode) return byCode.id;

  // 2. Specific prefix alias transforms with two-digit zero padding
  const cryptoMatch = clean.match(/^CRYPTO[-_]?(\d+)$/i);
  if (cryptoMatch) return `CRY-${cryptoMatch[1].padStart(2, '0')}`;

  const linkMatch = clean.match(/^LINK[-_]?(\d+)$/i);
  if (linkMatch) return `LNK-${linkMatch[1].padStart(2, '0')}`;

  const injMatch = clean.match(/^(?:INJ|INJECTION)[-_]?(\d+)$/i);
  if (injMatch) return `LLM-${injMatch[1].padStart(2, '0')}`;

  // 3. Generic standard prefix zero padding (e.g. HDR-1 -> HDR-01, BEC-4 -> BEC-04)
  const standardMatch = clean.match(/^([A-Z]+)[-_](\d+)$/);
  if (standardMatch) {
    const prefix = standardMatch[1];
    const num = standardMatch[2].padStart(2, '0');
    return `${prefix}-${num}`;
  }

  return clean;
}

/**
 * Maps a canonical vector ID to its prompt/external test alias ID.
 * - 'CRY-01' -> 'CRYPTO-01'
 * - 'LNK-01' -> 'LINK-01'
 * - 'LLM-01' -> 'INJ-01'
 */
export function toAliasVectorId(canonicalId: string): string {
  if (!canonicalId || typeof canonicalId !== 'string') return '';
  const clean = canonicalId.trim().toUpperCase();

  if (clean.startsWith('CRY-')) return clean.replace('CRY-', 'CRYPTO-');
  if (clean.startsWith('LNK-')) return clean.replace('LNK-', 'LINK-');
  if (clean.startsWith('LLM-')) return clean.replace('LLM-', 'INJ-');

  return clean;
}

// Pre-computed lookup hash tables for O(1) resolution
const VECTOR_BY_ID = new Map<string, EmailThreatVector>();
const VECTOR_BY_CODE = new Map<string, EmailThreatVector>();
const VECTOR_BY_ALIAS = new Map<string, EmailThreatVector>();

function initVectorMaps(): void {
  if (VECTOR_BY_ID.size > 0) return;
  EMAIL_THREAT_VECTORS_CATALOG.forEach(vector => {
    VECTOR_BY_ID.set(vector.id.toUpperCase(), vector);
    VECTOR_BY_CODE.set(vector.code.toUpperCase(), vector);

    if (vector.aliases) {
      vector.aliases.forEach(alias => {
        VECTOR_BY_ALIAS.set(alias.toUpperCase(), vector);
      });
    }

    // Auto-register canonical prefix aliases
    if (vector.id.startsWith('CRY-')) {
      VECTOR_BY_ALIAS.set(vector.id.replace('CRY-', 'CRYPTO-'), vector);
    } else if (vector.id.startsWith('LNK-')) {
      VECTOR_BY_ALIAS.set(vector.id.replace('LNK-', 'LINK-'), vector);
    } else if (vector.id.startsWith('LLM-')) {
      VECTOR_BY_ALIAS.set(vector.id.replace('LLM-', 'INJ-'), vector);
    }
  });
}

/**
 * Universal vector resolver. Looks up by:
 * 1. Exact vector code (e.g. 'SPF_HARD_FAIL')
 * 2. Exact canonical ID (e.g. 'HDR-01', 'CRY-01')
 * 3. Registered alias (e.g. 'CRYPTO-01', 'LINK-01', 'INJ-01', 'SCAN_QR_CODE')
 * 4. Normalized identifier (e.g. 'crypto-1', 'link-05')
 */
export function findVector(query: string): EmailThreatVector | undefined {
  if (!query || typeof query !== 'string') return undefined;
  initVectorMaps();
  const q = query.trim().toUpperCase();

  // 1. Direct code lookup
  const byCode = VECTOR_BY_CODE.get(q);
  if (byCode) return byCode;

  // 2. Direct ID lookup
  const byId = VECTOR_BY_ID.get(q);
  if (byId) return byId;

  // 3. Direct alias lookup
  const byAlias = VECTOR_BY_ALIAS.get(q);
  if (byAlias) return byAlias;

  // 4. Normalized ID lookup
  const normalizedId = normalizeVectorId(q);
  if (normalizedId) {
    const byNormId = VECTOR_BY_ID.get(normalizedId);
    if (byNormId) return byNormId;
  }

  // 5. Fallback linear search for partial / legacy compatibility
  return EMAIL_THREAT_VECTORS_CATALOG.find(v => 
    v.code.toUpperCase() === q ||
    v.id.toUpperCase() === q ||
    (v.aliases && v.aliases.some(a => a.toUpperCase() === q))
  );
}

